#!/usr/bin/env python3
"""Generate Android resources from the iOS asset catalog.

- Category line icons (cat-*.imageset/icon.svg) -> res/drawable/cat_*.xml vector drawables
- AppIcon.png -> launcher icons (adaptive foreground plus legacy PNGs) and a 512px Play Store icon
- critter-logo.png -> res/drawable-nodpi/critter_logo.png

Run from the repo root:  python3 scripts/android_assets.py
"""
import re
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
XC = ROOT / "TriviaNight/Resources/Assets.xcassets"
RES = ROOT / "android/app/src/main/res"
PLAY = ROOT / "android/play"


def f(x: float) -> str:
    return f"{x:g}"


def circle_path(cx, cy, r):
    return (f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0"
            f"a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0z")


def rect_path(x, y, w, h, rx):
    if not rx:
        return f"M{f(x)},{f(y)}h{f(w)}v{f(h)}h{f(-w)}z"
    return (f"M{f(x + rx)},{f(y)}h{f(w - 2 * rx)}a{f(rx)},{f(rx)} 0 0,1 {f(rx)},{f(rx)}"
            f"v{f(h - 2 * rx)}a{f(rx)},{f(rx)} 0 0,1 {f(-rx)},{f(rx)}"
            f"h{f(-(w - 2 * rx))}a{f(rx)},{f(rx)} 0 0,1 {f(-rx)},{f(-rx)}"
            f"v{f(-(h - 2 * rx))}a{f(rx)},{f(rx)} 0 0,1 {f(rx)},{f(-rx)}z")


def svg_to_vector(svg: Path) -> str:
    root = ET.parse(svg).getroot()
    sw = root.get("stroke-width", "1.8")
    paths = []
    for el in root:
        tag = el.tag.split("}")[-1]
        g = lambda k, d=0: float(el.get(k, d))
        if tag == "path":
            paths.append(el.get("d"))
        elif tag == "circle":
            paths.append(circle_path(g("cx"), g("cy"), g("r")))
        elif tag == "rect":
            paths.append(rect_path(g("x"), g("y"), g("width"), g("height"), g("rx")))
        else:
            raise SystemExit(f"{svg}: unsupported element {tag}")
    body = "\n".join(
        f'    <path android:pathData="{d}" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"\n'
        f'        android:strokeWidth="{sw}" android:strokeLineCap="round" android:strokeLineJoin="round" />'
        for d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/android_assets.py from the iOS asset catalog. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp"\n'
        '    android:viewportWidth="24" android:viewportHeight="24">\n'
        f"{body}\n</vector>\n"
    )


def main():
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    for svg in sorted(XC.glob("cat-*.imageset/icon.svg")):
        name = svg.parent.name.removesuffix(".imageset").replace("-", "_")
        (RES / "drawable" / f"{name}.xml").write_text(svg_to_vector(svg))

    nodpi = RES / "drawable-nodpi"
    nodpi.mkdir(parents=True, exist_ok=True)
    shutil.copy(XC / "critter-logo.imageset/critter-logo.png", nodpi / "critter_logo.png")

    icon = Image.open(XC / "AppIcon.appiconset/AppIcon.png").convert("RGB")
    bg = icon.getpixel((4, 4))

    # Adaptive icon: 108dp canvas, the full iOS icon scaled into the central 72dp.
    # The icon's own amber edge blends into the amber background layer.
    for density, scale in {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}.items():
        d = RES / f"mipmap-{density}"
        d.mkdir(parents=True, exist_ok=True)
        canvas = round(108 * scale)
        inner = round(72 * scale)
        fg = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
        fg.paste(icon.resize((inner, inner), Image.LANCZOS), ((canvas - inner) // 2,) * 2)
        fg.save(d / "ic_launcher_foreground.png")
        legacy = round(48 * scale)
        icon.resize((legacy, legacy), Image.LANCZOS).save(d / "ic_launcher.png")

    values = RES / "values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">#{bg[0]:02X}{bg[1]:02X}{bg[2]:02X}</color>\n'
        "</resources>\n"
    )

    PLAY.mkdir(parents=True, exist_ok=True)
    icon.resize((512, 512), Image.LANCZOS).save(PLAY / "icon-512.png")
    print("Android assets written.")


if __name__ == "__main__":
    main()
